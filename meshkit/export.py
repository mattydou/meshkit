"""Export: OBJ (+ MTL), JSON (lossless: verts, faces, loose edges, groups, UVs, material), GLB (gltf.py) and a small
Blender import script for the JSON. Import: load_obj (meshes from other tools), from_json, load_glb."""
import json
import os

import numpy as np

from .mesh import Mesh

_BLENDER_SCRIPT = '''"""Auto-generated by meshkit. Builds object {name!r} from {json_name}.
Run inside Blender: Text Editor > Run Script, or `blender --python {script_name}`.
Every group becomes a vertex group (face groups from their faces' verts), so a part is selectable in Edit Mode:
Object Data > Vertex Groups > pick it > Select. Face groups are also boolean face attributes '<group>_faces'.
UVs become the 'UVMap' layer; baked maps listed in the JSON become a Principled BSDF material.
SPLIT_PARTS = True imports each part as its own object (a face's part = its smallest face group)."""
import json
import os

import bpy

JSON_PATH = {json_path!r}
NAME = {name!r}
REPLACE = False      # True: delete existing objects called NAME / NAME.<part> first
SPLIT_PARTS = False  # True: one object per part, for quick inspection


def load(path=JSON_PATH):
    if not os.path.exists(path):
        try:
            path = os.path.join(os.path.dirname(os.path.abspath(__file__)), {json_name!r})
        except NameError:
            pass
    with open(path) as fh:
        return json.load(fh), os.path.dirname(os.path.abspath(path))


def split_faces(d):
    """{{part: [face ids]}}: each face goes to its smallest face group (first by name on ties); ungrouped faces
    go to 'rest'."""
    groups = sorted(((n, g["indices"]) for n, g in d["groups"].items() if g["kind"] == "face"),
                    key=lambda kv: (len(kv[1]), kv[0]))
    owner = [None] * len(d["faces"])
    for n, idx in groups:
        for i in idx:
            if owner[i] is None:
                owner[i] = n
    parts = {{}}
    for i, n in enumerate(owner):
        parts.setdefault(n or "rest", []).append(i)
    return parts


def subset(d, faces):
    """(verts, faces, loose edges, uvs, groups) for the given faces, verts renumbered (all of d if faces is None)."""
    uvs = d.get("uvs")
    if faces is None:
        return d["verts"], d["faces"], d["loose_edges"], uvs, {{n: (g["kind"], g["indices"]) for n, g in
                                                             d["groups"].items()}}
    used = sorted({{v for i in faces for v in d["faces"][i]}})
    vnew = {{v: k for k, v in enumerate(used)}}
    fnew = {{f: k for k, f in enumerate(faces)}}
    groups = {{}}
    for n, g in d["groups"].items():
        keep = vnew if g["kind"] == "vert" else fnew
        idx = [keep[i] for i in g["indices"] if i in keep]
        if idx:
            groups[n] = (g["kind"], idx)
    return ([d["verts"][v] for v in used], [[vnew[v] for v in d["faces"][i]] for i in faces], [],
            [uvs[i] for i in faces] if uvs else None, groups)


def material(d, root, name):
    """Principled BSDF fed by the baked maps (albedo, roughness, normal), or None when the JSON lists none."""
    maps = d.get("material")
    if not maps:
        return None
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = next(n for n in nt.nodes if n.type == "BSDF_PRINCIPLED")
    bsdf.inputs["Metallic"].default_value = 0.0

    def image(key, y, data):
        tex = nt.nodes.new("ShaderNodeTexImage")
        tex.image = bpy.data.images.load(os.path.join(root, maps[key]), check_existing=True)
        if data:
            tex.image.colorspace_settings.name = "Non-Color"
        tex.location = (-650, y)
        return tex
    if "albedo" in maps:
        nt.links.new(image("albedo", 300, False).outputs["Color"], bsdf.inputs["Base Color"])
    if "roughness" in maps:
        nt.links.new(image("roughness", 0, True).outputs["Color"], bsdf.inputs["Roughness"])
    if "normal" in maps:
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nm.location = (-300, -300)
        nt.links.new(image("normal", -300, True).outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    return mat


def make_object(name, verts, faces, loose, uvs, groups, mat, collection):
    if REPLACE and name in bpy.data.objects:
        bpy.data.objects.remove(bpy.data.objects[name], do_unlink=True)
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, loose, faces)
    if uvs:
        flat = []
        for f, uv in zip(faces, uvs):
            flat += uv if uv else [0.0] * (2 * len(f))
        me.uv_layers.new(name="UVMap").data.foreach_set("uv", flat)
    me.update()
    ob = bpy.data.objects.new(name, me)
    collection.objects.link(ob)
    for gname, (kind, idx) in groups.items():
        vs = idx if kind == "vert" else sorted({{v for i in idx for v in faces[i]}})
        ob.vertex_groups.new(name=gname).add(vs, 1.0, "REPLACE")
        if kind == "face":
            attr = me.attributes.new(name=gname + "_faces", type="BOOLEAN", domain="FACE")
            vals = [False] * len(me.polygons)
            for i in idx:
                vals[i] = True
            attr.data.foreach_set("value", vals)
    if mat:
        me.materials.append(mat)
    return ob


def build(path=JSON_PATH, name=NAME, split=None):
    d, root = load(path)
    split = SPLIT_PARTS if split is None else split
    mat = material(d, root, name)
    scene = bpy.context.collection or bpy.context.scene.collection
    if not split:
        return [make_object(name, *subset(d, None), mat, scene)]
    coll = bpy.data.collections.new(name)
    scene.children.link(coll)
    return [make_object(f"{{name}}.{{part}}", *subset(d, faces), mat, coll) for part, faces in split_faces(d).items()]


if __name__ == "__main__":
    build()
'''


def _uv_rows(mesh):
    """Per face: its corner UVs as a list, or None (no UVs on that face / mesh)."""
    if mesh.uvs is None:
        return [None] * len(mesh.faces)
    cs, U = mesh.corner_start, mesh.uvs
    return [None if np.isnan(U[cs[i]:cs[i + 1]]).any() else U[cs[i]:cs[i + 1]].tolist() for i in range(len(mesh.faces))]


def write_mtl(path, name, maps):
    """Write a .mtl with one material `name` using map files {albedo, roughness, normal} (paths relative to it)."""
    lines = ["# meshkit MTL", f"newmtl {name}", "Ka 0 0 0", "Kd 1 1 1", "Ks 0 0 0", "Ns 10", "d 1", "illum 2",
             "Pm 0"]
    if "albedo" in maps:
        lines.append(f"map_Kd {maps['albedo']}")
    if "roughness" in maps:
        lines += ["Pr 1", f"map_Pr {maps['roughness']}"]
    if "normal" in maps:
        lines += [f"norm {maps['normal']}", f"map_Bump -bm 1.0 {maps['normal']}"]
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def to_obj(mesh, path, y_up=True, material=None):
    """Write OBJ: faces, UVs ('vt', when the mesh has them), loose edges ('l'), face groups as 'g' lines. y_up=True
    writes (x, z, -y) so default OBJ importers (Blender's included) show the Z-up model upright.
    material = {'name': ..., 'albedo' / 'roughness' / 'normal': map file names} also writes <obj name>.mtl."""
    V = mesh.verts[:, [0, 2, 1]] * (1, 1, -1) if y_up else mesh.verts
    member = [sorted(n for n, g in mesh.groups.items() if g.kind == "f" and i in g.idx) for i in range(len(mesh.faces))]
    lines = ["# meshkit OBJ"]
    if material:
        mtl = os.path.splitext(str(path))[0] + ".mtl"
        write_mtl(mtl, material.get("name", "material"), material)
        lines.append(f"mtllib {os.path.basename(mtl)}")
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in V]
    rows = _uv_rows(mesh)
    vt = {}
    for uv in rows:
        for u, v in uv or ():
            vt.setdefault((round(u, 6), round(v, 6)), len(vt) + 1)
    lines += [f"vt {u:.6f} {v:.6f}" for u, v in vt]
    if material:
        lines.append(f"usemtl {material.get('name', 'material')}")
    cur, grouped = None, any(member)
    for f, names, uv in zip(mesh.faces, member, rows):
        if grouped and names != cur:
            lines.append("g " + (" ".join(names) if names else "ungrouped"))
            cur = names
        if uv is None:
            lines.append("f " + " ".join(str(v + 1) for v in f))
        else:
            lines.append("f " + " ".join(f"{v + 1}/{vt[(round(a, 6), round(b, 6))]}" for v, (a, b) in zip(f, uv)))
    lines += [f"l {a + 1} {b + 1}" for a, b in sorted(mesh.loose_edges)]
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def to_dict(mesh, material=None):
    d = {
        "verts": mesh.verts.tolist(),
        "faces": [list(f) for f in mesh.faces],
        "loose_edges": [list(e) for e in sorted(mesh.loose_edges)],
        "groups": {n: {"kind": "vert" if g.kind == "v" else "face", "indices": sorted(g.idx)}
                   for n, g in sorted(mesh.groups.items())},
    }
    if mesh.uvs is not None:
        d["uvs"] = [None if uv is None else [c for p in uv for c in p] for uv in _uv_rows(mesh)]
    if material:
        d["material"] = material
    return d


def to_json(mesh, path, material=None):
    """Write lossless JSON: verts, faces, loose_edges, groups {name: {kind: vert|face, indices}}, uvs (per face: flat
    [u0, v0, u1, v1, ...] or null) and material (map file names, for the Blender script)."""
    with open(path, "w", newline="\n") as fh:
        fh.write(json.dumps(to_dict(mesh, material), separators=(",", ":")))
    return path


def from_json(path):
    """Read a mesh written by to_json."""
    with open(path) as fh:
        d = json.load(fh)
    groups = {n: (g["kind"], g["indices"]) for n, g in d.get("groups", {}).items()}
    uvs = d.get("uvs")
    if uvs is not None:
        uvs = [None if u is None else np.array(u, dtype=float).reshape(-1, 2) for u in uvs]
    return Mesh(np.array(d["verts"], dtype=float).reshape(-1, 3), d["faces"], d.get("loose_edges", ()), groups, uvs)


def load_obj(path, y_up=True):
    """Read an OBJ from any tool: v, vt (UVs per face corner), f (v/vt/vn and negative indices ok), l (loose edges);
    g and o names become face groups. y_up=True converts Y-up files (Blender's default export, and to_obj) back to
    Z up. Faces with < 3 distinct verts are dropped; check() reports the rest."""
    V, T, F, FU, L, groups = [], [], [], [], [], {}
    cur, obj = [], []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            parts = line.split()
            if not parts or parts[0].startswith("#"):
                continue
            tag = parts[0]
            if tag == "v":
                V.append([float(x) for x in parts[1:4]])
            elif tag == "vt":
                T.append([float(x) for x in (parts[1:3] + ["0"])[:2]])
            elif tag in ("f", "l"):
                refs = [p.split("/") for p in parts[1:]]
                idx = [int(r[0]) for r in refs]
                idx = [i - 1 if i > 0 else len(V) + i for i in idx]
                if tag == "l":
                    L += [(a, b) for a, b in zip(idx, idx[1:]) if a != b]
                elif len(set(idx)) >= 3:
                    for n in cur + obj:
                        groups.setdefault(n, []).append(len(F))
                    F.append(idx)
                    ts = [int(r[1]) if len(r) > 1 and r[1] else None for r in refs]
                    FU.append(None if None in ts else [T[t - 1 if t > 0 else len(T) + t] for t in ts])
            elif tag == "g":
                cur = [n for n in parts[1:] if n not in ("default", "ungrouped", "off")]
            elif tag == "o":
                obj = parts[1:2]
    P = np.array(V, dtype=float).reshape(-1, 3)
    if y_up:
        P = P[:, [0, 2, 1]] * (1, -1, 1)
    uvs = FU if any(u is not None for u in FU) else None
    return Mesh(P, F, L, {n: ("f", idx) for n, idx in groups.items()}, uvs)


def write_blender_script(json_path, script_path, name):
    """Write a Blender Python script that imports json_path as object `name`."""
    text = _BLENDER_SCRIPT.format(name=name, json_path=os.path.abspath(json_path),
                                  json_name=os.path.basename(json_path), script_name=os.path.basename(script_path))
    with open(script_path, "w", newline="\n") as fh:
        fh.write(text)
    return script_path


def _maps(bake, out_dir, name):
    """{map: file name in out_dir} for a bake, writing the PNGs there unless the bake already did."""
    from .png import write_png
    maps = {}
    for key in ("albedo", "roughness", "normal"):
        path = bake.paths.get(key)
        if not path or os.path.abspath(os.path.dirname(path)) != os.path.abspath(out_dir):
            path = write_png(os.path.join(out_dir, f"{name}_{key}.png"), getattr(bake, key))
        maps[key] = os.path.basename(path)
    return maps


def export_all(mesh, out_dir, name, bake=None):
    """Write <name>.obj, .json, _blender.py and .glb into out_dir; with a bake also the maps (<name>_albedo.png ...),
    an .mtl, and the material in the JSON (the Blender script builds it) and the GLB. Returns the paths."""
    from .gltf import to_glb
    os.makedirs(out_dir, exist_ok=True)
    base = os.path.join(out_dir, name)
    material = dict(name=name, **_maps(bake, out_dir, name)) if bake is not None else None
    j = to_json(mesh, base + ".json", material)
    out = [to_obj(mesh, base + ".obj", material=material), j, write_blender_script(j, base + "_blender.py", name),
           to_glb(mesh, base + ".glb", bake, name)]
    if material:
        out += [base + ".mtl"] + [os.path.join(out_dir, material[k]) for k in ("albedo", "roughness", "normal")]
    return out
